import './_boot';
import { World } from '../src/core/world';
import { ControlModule } from '../src/core/control';
import { legLevelingJacobian } from '../src/core/servo/legLevelingJacobian';
const w = new World();
const ctl = new ControlModule(w);
w.reset(); w.switchPoseState('stand');
for (let i = 0; i < 60; i++) w.advance(1);
const pose = ctl.footAnkle.world.pose.get('l');
console.log('pose', JSON.stringify(pose ?? null));
const bi = w.body.indexByKey.get('foot_l');
const actual = bi !== undefined ? w.body.bodies[bi]!.rotation() : null;
console.log('actual', JSON.stringify(actual));
const targetQ = pose?.q ?? actual ?? { x: 0, y: 0, z: 0, w: 1 };
console.log(JSON.stringify(legLevelingJacobian({ w, side: 'l', targetQ, kp: 100, kd: 10, cap: 20 })));
