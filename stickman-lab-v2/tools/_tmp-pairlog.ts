import './_boot';
import { World } from '../src/core/world';
import { ControlModule } from '../src/core/control';
const g = globalThis as any;
g.__PAIRDBG = [];
const w = new World();
const ctl = new ControlModule(w, { postureTone: 8 });
w.controller = ctl;
w.reset();
ctl.actions.play('singleLegR');
for (let s = 0; s < Math.round(3.2 / w.dt); s++) w.advance(1);
console.log('pair calls on hip_r:', g.__PAIRDBG.length);
for (const r of g.__PAIRDBG.slice(-5)) console.log('c=' + r[0].toFixed(2), 'ref=' + (r[1] ?? 0).toFixed(3), 'ang=' + (r[2] * 57.3).toFixed(1), 'vel=' + r[3].toFixed(1), 'tq=' + r[4].toFixed(1));
